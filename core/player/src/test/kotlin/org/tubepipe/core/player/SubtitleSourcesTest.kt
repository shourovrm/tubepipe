package org.tubepipe.core.player

import org.junit.Assert.assertEquals
import org.junit.Test
import org.schabi.newpipe.extractor.MediaFormat
import org.schabi.newpipe.extractor.stream.SubtitlesStream

class SubtitleSourcesTest {
    @Test
    fun tagsThatShowTheSameNameKeepOneTrack() {
        // "en-US" and "en-us" are different tags but both name "English (United States)", so the menu would show
        // that label twice.
        val chosen = SubtitleSources.choose(
            listOf(subtitle("en-US", autoGenerated = false), subtitle("en-us", autoGenerated = false)),
        )

        assertEquals(listOf("en-US"), chosen.map { it.languageTag })
    }

    @Test
    fun uploadedTrackReplacesAutoGeneratedTrackWithSameName() {
        val chosen = SubtitleSources.choose(
            listOf(subtitle("en-us", autoGenerated = true), subtitle("en-US", autoGenerated = false)),
        )

        assertEquals(listOf(false), chosen.map { it.isAutoGenerated })
    }

    @Test
    fun differentNamesStayAsSeparateTracks() {
        val chosen = SubtitleSources.choose(
            listOf(subtitle("en", autoGenerated = false), subtitle("en-US", autoGenerated = false)),
        )

        assertEquals(listOf("en", "en-US"), chosen.map { it.languageTag })
    }

    private fun subtitle(languageCode: String, autoGenerated: Boolean): SubtitlesStream = SubtitlesStream.Builder()
        .setContent("https://example.com/$languageCode/$autoGenerated.vtt", true)
        .setMediaFormat(MediaFormat.VTT)
        .setLanguageCode(languageCode)
        .setAutoGenerated(autoGenerated)
        .build()
}
