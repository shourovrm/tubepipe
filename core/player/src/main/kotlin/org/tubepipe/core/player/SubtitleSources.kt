package org.tubepipe.core.player

import androidx.annotation.OptIn
import androidx.media3.common.Format
import androidx.media3.common.MediaItem
import androidx.media3.common.MimeTypes
import androidx.media3.common.util.UnstableApi
import androidx.media3.datasource.DataSource
import androidx.media3.exoplayer.source.MediaSource
import androidx.media3.exoplayer.source.MergingMediaSource
import androidx.media3.exoplayer.source.ProgressiveMediaSource
import androidx.media3.extractor.Extractor
import androidx.media3.extractor.ExtractorsFactory
import androidx.media3.extractor.text.DefaultSubtitleParserFactory
import androidx.media3.extractor.text.SubtitleExtractor
import org.schabi.newpipe.extractor.MediaFormat
import org.schabi.newpipe.extractor.stream.SubtitlesStream

/** Side-loads the extractor's subtitles next to a built media source, whatever its delivery. */
@OptIn(UnstableApi::class)
object SubtitleSources {
    private const val AUTO_GENERATED_SUFFIX = " (auto-generated)"
    private val subtitleParserFactory = DefaultSubtitleParserFactory()

    /** Returns [mediaSource] unchanged when the video has no usable subtitles. */
    fun attach(
        mediaSource: MediaSource,
        subtitles: List<SubtitlesStream>,
        dataSourceFactory: DataSource.Factory,
    ): MediaSource {
        val chosen = choose(subtitles)
        if (chosen.isEmpty()) {
            return mediaSource
        }
        val subtitleSources = chosen.map { subtitle -> parsedSubtitleSource(subtitle, dataSourceFactory) }
        return MergingMediaSource(mediaSource, *subtitleSources.toTypedArray())
    }

    /**
     * A source that parses the subtitle file into cues while reading it, the way Media3's DefaultMediaSourceFactory
     * side-loads subtitles. Media3's text renderer only accepts parsed cues: a raw TTML or VTT sample made it throw
     * "Legacy decoding is disabled", which stopped SABR playback as soon as a caption was picked.
     */
    private fun parsedSubtitleSource(subtitle: SubtitlesStream, dataSourceFactory: DataSource.Factory): MediaSource {
        val plainFormat = Format.Builder()
            .setSampleMimeType(mimeTypeOf(subtitle))
            .setLanguage(subtitle.languageTag)
            .setLabel(labelOf(subtitle))
            .build()
        val format = plainFormat.buildUpon()
            .setCueReplacementBehavior(subtitleParserFactory.getCueReplacementBehavior(plainFormat))
            .build()
        val extractorsFactory = ExtractorsFactory {
            arrayOf<Extractor>(SubtitleExtractor(subtitleParserFactory.create(format), format))
        }
        return ProgressiveMediaSource.Factory(dataSourceFactory, extractorsFactory)
            .createMediaSource(MediaItem.fromUri(subtitle.content))
    }

    /**
     * One subtitle per language, uploaded ones before auto-generated ones; an auto-generated track is kept only for
     * a language that has no uploaded track. Only VTT and TTML are used because Media3 parses those two.
     */
    fun choose(subtitles: List<SubtitlesStream>): List<SubtitlesStream> {
        val playable = subtitles.filter { subtitle -> subtitle.isUrl && mimeTypeOf(subtitle) != null }
        val bestPerLanguageAndKind = playable
            .groupBy { subtitle -> subtitle.languageTag to subtitle.isAutoGenerated }
            .values
            .map { sameLanguageAndKind -> sameLanguageAndKind.minBy { subtitle -> formatRank(subtitle) } }
        val uploadedLanguages = bestPerLanguageAndKind
            .filter { subtitle -> !subtitle.isAutoGenerated }
            .map { subtitle -> subtitle.languageTag }
            .toSet()
        return bestPerLanguageAndKind
            .filter { subtitle -> !subtitle.isAutoGenerated || subtitle.languageTag !in uploadedLanguages }
            .sortedBy { subtitle -> subtitle.isAutoGenerated }
    }

    private fun formatRank(subtitle: SubtitlesStream): Int = if (subtitle.format == MediaFormat.VTT) 0 else 1

    private fun mimeTypeOf(subtitle: SubtitlesStream): String? = when (subtitle.format) {
        MediaFormat.VTT -> MimeTypes.TEXT_VTT
        MediaFormat.TTML -> MimeTypes.APPLICATION_TTML
        else -> null
    }

    private fun labelOf(subtitle: SubtitlesStream): String {
        val name = subtitle.displayLanguageName.ifBlank { subtitle.languageTag }
        return if (subtitle.isAutoGenerated) name + AUTO_GENERATED_SUFFIX else name
    }
}
